/**
 * Triggers a direct browser file download of the generated Deriv DBot XML file
 */
export function downloadDerivBotXmlFile(options: BotExportOptions, customFileName?: string) {
  const xmlContent = generateDerivBotXml(options);
  const fileName =
    customFileName ||
    `Deriv_Under8_Sniper_Bot_${options.symbolId}_${options.stakeStrategy}.xml`;

  const blob = new Blob([xmlContent], { type: 'application/xml;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', fileName);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

