export function downloadDerivEvenOddBotXmlFile(options: EvenOddBotExportOptions, customFileName?: string) {
  const xmlContent = generateDerivEvenOddBotXml(options);
  const fileName =
    customFileName ||
    `Deriv_EvenOdd_95Precision_Bot_${options.symbolId}_${options.targetParity}.xml`;

  const blob = new Blob([xmlContent], { type: 'application/xml;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', fileName);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
